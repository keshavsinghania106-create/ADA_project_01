-- Additive support for one public PNR containing multiple train bookings.
-- Run once in pgAdmin against the same database as the existing Railflow schema.
-- Existing tables, functions, triggers, and occupancy rows are not changed.

CREATE TABLE IF NOT EXISTS public.journey_bookings (
    journey_booking_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pnr varchar(10) NOT NULL UNIQUE,
    booking_status varchar(20) NOT NULL DEFAULT 'PENDING'
        CHECK (booking_status IN ('PENDING', 'CONFIRMED', 'CANCELLED')),
    booking_time timestamp without time zone NOT NULL DEFAULT now(),
    cancelled_at timestamp without time zone
);

CREATE TABLE IF NOT EXISTS public.journey_legs (
    journey_leg_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journey_booking_id bigint NOT NULL
        REFERENCES public.journey_bookings(journey_booking_id),
    leg_order smallint NOT NULL CHECK (leg_order > 0),
    booking_id bigint NOT NULL UNIQUE REFERENCES public.bookings(booking_id),
    CONSTRAINT uq_journey_leg_order UNIQUE (journey_booking_id, leg_order)
);

CREATE INDEX IF NOT EXISTS idx_journey_legs_parent
    ON public.journey_legs(journey_booking_id, leg_order);
